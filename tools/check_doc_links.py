"""Check local Markdown/HTML links in publishable documentation, without network."""
from pathlib import Path
import re
import subprocess
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]


def main():
    files = subprocess.check_output(
        ['git', 'ls-files', '--cached', '--others', '--exclude-standard', '-z'], cwd=ROOT
    ).decode().split('\0')
    errors = []
    checked = 0
    for name in sorted(set(filter(None, files))):
        path = ROOT / name
        if path.suffix not in ('.md', '.html') or not path.is_file():
            continue
        if path.suffix == '.html' and not name.startswith('docs/'):
            continue  # Flutter web templates refer to files generated by build.
        text = path.read_text()
        links = re.findall(r'!?\[[^\]\n]*\]\(([^)\n]+)\)', text)
        links += re.findall(r'(?:src|href)=["\']([^"\']+)["\']', text)
        for link in links:
            link = link.strip().strip('<>')
            if ' "' in link:
                link = link.split(' "', 1)[0]
            parts = urlsplit(link)
            if parts.scheme or parts.netloc or not parts.path:
                continue
            target = (path.parent / unquote(parts.path)).resolve()
            checked += 1
            if not target.exists():
                errors.append(f'{name}: {link}')
    for error in errors:
        print(error)
    print(f'Local documentation links: {checked}; broken: {len(errors)}')
    return int(bool(errors))


if __name__ == '__main__':
    raise SystemExit(main())
